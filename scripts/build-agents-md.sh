#!/usr/bin/env bash
# Generate the concise portable agent router from canonical plugin components.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/AGENTS.md"

title_for() {
  local skill="$1"
  awk '
    NR == 1 && $0 == "---" { frontmatter = 1; next }
    frontmatter && $0 == "---" { frontmatter = 0; next }
    !frontmatter && /^# / { sub(/^# /, ""); print; exit }
  ' "$ROOT/skills/$skill/SKILL.md"
}

skill_item() {
  local skill="$1"
  local title
  title="$(title_for "$skill")"
  printf -- '- [%s](skills/%s/SKILL.md) — `%s`\n' "$title" "$skill" "$skill"
}

render() {
  cat <<'EOF'
<!-- GENERATED by scripts/build-agents-md.sh — DO NOT EDIT. -->

# QaaS Platform Development — Agent Guide

This repository is the portable source for the `qaas-platform-dev` plugin.
Canonical instructions live in `skills/`; this file only routes agents to the
right owner and must stay concise.

Outside Claude Code, resolve `${CLAUDE_PLUGIN_ROOT}` in linked skill commands to
the checkout directory that contains this guide.

## Mandatory entry

Read [Know QaaS](skills/qaas-platform-overview/SKILL.md) first for every QaaS
platform task. Produce its context brief before planning, implementing,
verifying, releasing, or answering ownership questions. Repository instructions
and live source override memory and volatile inventories in this plugin.

## Change lifecycle

1. Understand QaaS and route the request.
2. Interview the developer and freeze an exact evidence-backed plan revision.
3. Review that revision independently.
4. Wait for explicit developer approval of the same revision.
5. Implement test-first only while the plan and repository baselines remain current.
6. Verify independently.
7. Release only when explicitly authorized.

The reviewed revision and content digest, developer-approved revision and digest,
and current plan must match. A material plan edit or source-baseline change stops
implementation and requires a new review and approval.

## External workflow providers

Planning interviews explicitly invoke `mattpocock-skills:grilling`. Planning,
implementation, independent review, and independent verification explicitly
invoke `ponytail:ponytail` with `full`. A successful call reports
`Provider: exact-skill-id — SUCCEEDED`; a post-load invocation failure reports
`BLOCKED_PROVIDER: exact-skill-id — cause` and stops without an internal
fallback. Provider output cannot bypass any QaaS lifecycle gate.

## Core workflow skills

EOF
  skill_item qaas-platform-overview
  skill_item develop-qaas-change
  skill_item plan-qaas-change
  skill_item implement-qaas-change
  skill_item release-and-mirror

  cat <<'EOF'

## Domain and evidence skills

EOF
  skill_item find-qaas-knowledge
  skill_item qaas-knowledge-graph
  skill_item add-framework-hook
  skill_item extend-framework-core

  cat <<'EOF'

## Independent agents

- [QaaS change planner](agents/qaas-change-planner.md) — read-only source investigation and draft.
- [QaaS plan reviewer](agents/qaas-plan-reviewer.md) — independent technical review of one frozen revision.
- [QaaS verifier](agents/qaas-verifier.md) — non-editing verification of the implemented change.

## Source-of-truth rule

Commands and `README.md` are entry points and summaries. They never override a
skill contract. Do not copy detailed repository behavior into this plugin; cite
the owning repository's current `CLAUDE.md`, `project_specs.md`, source, live
docs, or knowledge-graph provenance.
EOF
}

case "${1:-}" in
  "")
    render > "$OUT"
    echo "build-agents-md: wrote $OUT"
    ;;
  --check)
    tmp="$(mktemp)"
    trap 'rm -f "$tmp"' EXIT
    render > "$tmp"
    if ! cmp -s "$tmp" "$OUT"; then
      echo "build-agents-md: $OUT is stale" >&2
      diff -u "$OUT" "$tmp" || true
      exit 1
    fi
    echo "build-agents-md: OK"
    ;;
  *)
    echo "usage: $0 [--check]" >&2
    exit 2
    ;;
esac
